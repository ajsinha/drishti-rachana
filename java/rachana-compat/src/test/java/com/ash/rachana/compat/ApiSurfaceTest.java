package com.ash.rachana.compat;

import static org.junit.jupiter.api.Assertions.*;

import java.io.InputStream;
import java.lang.module.ModuleDescriptor;
import java.lang.reflect.*;
import java.nio.file.*;
import java.util.*;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;

/**
 * CG5, API surface (SUTRA_EXPANSION 6.5). {@code java/api-surface.txt} lists every public and protected member of every public class
 * in a package that {@code rachana-api} or {@code rachana-core} exports, one line each, sorted. The test builds the same list from the
 * compiled modules: a removed or changed signature fails, and so does an added one, so an addition updates the baseline in the same
 * commit and review sees it. A new abstract method on a host hook shows as a new line with {@code abstract}. To update the baseline
 * after a reviewed change run {@code ./mvnw -pl rachana-compat -am test -Drachana.api.surface.write=true}: it rewrites the file and
 * the test then passes; the diff is the review.
 */
class ApiSurfaceTest {
    static final List<String> MODULES = List.of("rachana-api", "rachana-core");

    static Path baseline() { return Corpus.repoRoot().resolve("java/api-surface.txt"); }

    /** The surface of the modules' compiled classes, one sorted line per class, constructor, method and field. */
    static List<String> surface(Path javaRoot) throws Exception {
        TreeSet<String> out = new TreeSet<>();
        for (String m : MODULES) {
            Path classes = javaRoot.resolve(m).resolve("target/classes");
            assertTrue(Files.isRegularFile(classes.resolve("module-info.class")), classes + " has no module-info.class: build first");
            ModuleDescriptor d;
            try (InputStream in = Files.newInputStream(classes.resolve("module-info.class"))) { d = ModuleDescriptor.read(in); }
            for (ModuleDescriptor.Exports e : d.exports()) {
                if (e.isQualified()) continue;
                Path pkg = classes.resolve(e.source().replace('.', '/'));
                try (Stream<Path> files = Files.list(pkg)) {
                    for (Path f : files.filter(x -> x.toString().endsWith(".class")).sorted().toList()) {
                        String n = f.getFileName().toString();
                        if (n.equals("package-info.class")) continue;
                        Class<?> c = Class.forName(e.source() + "." + n.substring(0, n.length() - 6), false, ApiSurfaceTest.class.getClassLoader());
                        describe(c, out);
                    }
                }
            }
        }
        return new ArrayList<>(out);
    }

    static boolean visible(int mod) { return Modifier.isPublic(mod) || Modifier.isProtected(mod); }

    static void describe(Class<?> c, Set<String> out) {
        if (!visible(c.getModifiers())) return;
        String owner = c.getName();
        out.add("class " + c.toGenericString());
        for (Constructor<?> k : c.getDeclaredConstructors()) if (visible(k.getModifiers())) out.add(owner + " :: " + k.toGenericString());
        for (Method m : c.getDeclaredMethods()) if (visible(m.getModifiers()) && !m.isSynthetic()) out.add(owner + " :: " + m.toGenericString());
        for (Field f : c.getDeclaredFields()) if (visible(f.getModifiers()) && !f.isSynthetic()) out.add(owner + " :: " + f.toGenericString());
        for (Class<?> n : c.getDeclaredClasses()) describe(n, out);
    }

    @Test
    void thePublicApiIsTheCommittedBaseline() throws Exception {
        List<String> now = surface(Corpus.repoRoot().resolve("java"));
        assertFalse(now.isEmpty(), "no public API found: the modules were not built");
        if (Boolean.getBoolean("rachana.api.surface.write")) {
            Files.writeString(baseline(), "# Generated by ApiSurfaceTest (CG5): the public and protected API of rachana-api and rachana-core. Review the diff; do not edit. EXPERIMENTAL until v1.0.0: the packages view, agg, bind, wire, profile, control and the parse additions may still change (owner, 2026-11-21).\n"
                + String.join("\n", now) + "\n");
        }
        List<String> was = Files.readAllLines(baseline()).stream().filter(l -> !l.startsWith("#") && !l.isBlank()).toList();
        List<String> removed = new ArrayList<>(was); removed.removeAll(now);
        List<String> added = new ArrayList<>(now); added.removeAll(was);
        assertEquals(List.of(), removed, "CG5: removed or changed API (a breaking change needs the owner)");
        assertEquals(List.of(), added, "CG5: added API: update java/api-surface.txt in the same commit (-Drachana.api.surface.write=true)");
    }

    @Test
    void theCheckSeesARemovalAndAnAddition() {
        List<String> was = List.of("a", "b");
        List<String> now = List.of("b", "c");
        List<String> removed = new ArrayList<>(was); removed.removeAll(now);
        List<String> added = new ArrayList<>(now); added.removeAll(was);
        assertEquals(List.of("a"), removed);
        assertEquals(List.of("c"), added);
    }
}
