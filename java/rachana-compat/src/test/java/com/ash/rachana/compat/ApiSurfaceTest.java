package com.ash.rachana.compat;

import static org.junit.jupiter.api.Assertions.*;

import java.io.InputStream;
import java.lang.module.ModuleDescriptor;
import java.lang.reflect.*;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.file.*;
import java.util.*;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;

/**
 * CG5, API surface (SUTRA_EXPANSION 6.5; gate 2 findings F11 and O9). {@code java/api-surface.txt} lists every public and protected
 * member of every public class in a package that one of the seven published modules exports ({@link #MODULES}), one line each, marked
 * {@code [stable]} or {@code [experimental]}: stable is the small entry surface frozen at {@code v1.0.0} ({@link #STABLE}), every
 * other line may change in a minor release (gate 2, section 4: hosts read the ViewModel as JSON, the frozen contract). The test builds
 * the same list from the compiled modules and fails on any difference, so an addition updates the baseline in the same commit and
 * review sees it.
 *
 * <p>Writing the baseline ({@code -Drachana.api.surface.write=true}) never removes silently: a line that disappears (or a stable line
 * that becomes experimental) must be listed in {@code java/api-removals.txt} with a date and a reason, the reviewed log of removals;
 * otherwise the write is refused and nothing is written. A released baseline ({@code java/api-surface-<minor>.txt}, copied at the tag
 * and never written by this test) is checked on every run: each of its stable lines must still be stable, and each of its
 * experimental lines present or logged in {@code api-removals.txt}.
 */
class ApiSurfaceTest {
    /** The published modules: every one of their exported packages is in the baseline. */
    static final List<String> MODULES = List.of("rachana-api", "rachana-core", "rachana-tools", "rachana-data", "rachana-live",
            "rachana-server", "rachana-cli");

    /** The classes frozen at v1.0.0 (gate 2, O9): the entry surface; their nested classes only when named. */
    static final Set<String> STABLE = Set.of("com.ash.rachana.api.Node", "com.ash.rachana.Rachana", "com.ash.rachana.RachanaOptions",
            "com.ash.rachana.RachanaCode", "com.ash.rachana.RachanaException", "com.ash.rachana.SutraException",
            "com.ash.rachana.SutraProblem", "com.ash.rachana.SutraProblem$Range", "com.ash.rachana.model.SourceLocation",
            "com.ash.rachana.el.ElCompiler", "com.ash.rachana.el.ElException", "com.ash.rachana.el.Expr", "com.ash.rachana.el.Template",
            "com.ash.rachana.el.EvalContext", "com.ash.rachana.el.ElFunction", "com.ash.rachana.el.FunctionTable",
            "com.ash.rachana.el.ElLimits", "com.ash.rachana.el.SafeRegex$Limits", "com.ash.rachana.format.Formats",
            "com.ash.rachana.lib.LibrarySet", "com.ash.rachana.lib.LibraryResolver", "com.ash.rachana.lib.Library",
            "com.ash.rachana.lib.Library$Trust");

    static final String S = "[stable] ", E = "[experimental] ";

    static final String HEADER = """
            # Generated by ApiSurfaceTest (CG5): the public and protected API of the seven published modules (rachana-api, -core, -tools,
            # -data, -live, -server, -cli), one line per class and member. Review the diff; do not edit by hand.
            # [stable]: frozen at v1.0.0 (gate 2, O9): Node, Rachana, RachanaOptions, RachanaCode, the exceptions, SutraProblem and its
            # Range, SourceLocation, ElCompiler, Expr, Template, EvalContext, ElFunction, FunctionTable, ElLimits, SafeRegex.Limits, Formats,
            # LibrarySet, LibraryResolver, Library and Library.Trust. A stable line is never removed or changed in 1.x.
            # [experimental]: may change in a minor release: view, bind, wire, control, agg, model, profile, parse, table, design, el.check
            # and the editor tools; rachana-tools, -server and -cli; rachana-data and rachana-live (live.spi: fix first, then freeze).
            # Hosts read the ViewModel as JSON (ViewJson): the schemas are the frozen contract, not these records.
            # Removing a line: list it in java/api-removals.txt with a date and a reason, then write; the write refuses otherwise.
            """;

    static Path javaRoot() { return Corpus.repoRoot().resolve("java"); }

    static Path baseline() { return javaRoot().resolve("api-surface.txt"); }

    static Path removals() { return javaRoot().resolve("api-removals.txt"); }

    /** The surface of the modules' compiled classes, marked, one sorted line per class, constructor, method and field. */
    static List<String> surface(Path javaRoot) throws Exception {
        List<URL> urls = new ArrayList<>();
        for (String m : MODULES) {
            urls.add(javaRoot.resolve(m).resolve("target/classes").toUri().toURL());
        }
        Path cp = javaRoot.resolve("rachana-data/target/runtime-classpath.txt");     // Arrow's jars, for rachana-data's signatures
        assertTrue(Files.isRegularFile(cp), cp + " is missing: build the reactor first (./mvnw verify)");
        for (String j : Files.readString(cp).strip().split(java.io.File.pathSeparator)) {
            if (!j.isBlank()) {
                urls.add(Path.of(j).toUri().toURL());
            }
        }
        TreeSet<String> stable = new TreeSet<>(), experimental = new TreeSet<>();
        try (URLClassLoader loader = new URLClassLoader(urls.toArray(URL[]::new), ApiSurfaceTest.class.getClassLoader())) {
            for (String m : MODULES) {
                Path classes = javaRoot.resolve(m).resolve("target/classes");
                assertTrue(Files.isRegularFile(classes.resolve("module-info.class")), classes + " has no module-info.class: build first");
                ModuleDescriptor d;
                try (InputStream in = Files.newInputStream(classes.resolve("module-info.class"))) { d = ModuleDescriptor.read(in); }
                for (ModuleDescriptor.Exports e : d.exports()) {
                    if (e.isQualified()) continue;
                    Path pkg = classes.resolve(e.source().replace('.', '/'));
                    try (Stream<Path> files = Files.list(pkg)) {
                        for (Path f : files.filter(x -> x.toString().endsWith(".class")).sorted().toList()) {
                            String n = f.getFileName().toString();
                            if (n.equals("package-info.class")) continue;
                            Class<?> c = Class.forName(e.source() + "." + n.substring(0, n.length() - 6), false, loader);
                            describe(c, stable, experimental);
                        }
                    }
                }
            }
        }
        List<String> out = new ArrayList<>();
        stable.forEach(l -> out.add(S + l));
        experimental.forEach(l -> out.add(E + l));
        return out;
    }

    static boolean visible(int mod) { return Modifier.isPublic(mod) || Modifier.isProtected(mod); }

    static void describe(Class<?> c, Set<String> stable, Set<String> experimental) {
        if (!visible(c.getModifiers())) return;
        String owner = c.getName();
        Set<String> out = STABLE.contains(owner) ? stable : experimental;
        out.add("class " + c.toGenericString());
        for (Constructor<?> k : c.getDeclaredConstructors()) if (visible(k.getModifiers())) out.add(owner + " :: " + k.toGenericString());
        for (Method m : c.getDeclaredMethods()) if (visible(m.getModifiers()) && !m.isSynthetic()) out.add(owner + " :: " + m.toGenericString());
        for (Field f : c.getDeclaredFields()) if (visible(f.getModifiers()) && !f.isSynthetic()) out.add(owner + " :: " + f.toGenericString());
        for (Class<?> n : c.getDeclaredClasses()) describe(n, stable, experimental);
    }

    /** The marked lines of a baseline file (comments and blank lines left out). */
    static List<String> lines(Path f) throws Exception {
        return Files.readAllLines(f).stream().filter(l -> !l.startsWith("#") && !l.isBlank()).toList();
    }

    static String bare(String marked) {
        return marked.startsWith(S) ? marked.substring(S.length()) : marked.startsWith(E) ? marked.substring(E.length()) : marked;
    }

    /**
     * What going from {@code was} to {@code now} removes: a line whose signature is gone, and a stable line that is no longer stable
     * (a promotion from experimental to stable is an addition).
     */
    static List<String> removed(List<String> was, List<String> now) {
        Set<String> nowSet = new HashSet<>(now), nowBare = new HashSet<>();
        now.forEach(l -> nowBare.add(bare(l)));
        List<String> out = new ArrayList<>();
        for (String l : was) {
            if (!nowBare.contains(bare(l)) || (l.startsWith(S) && !nowSet.contains(l))) out.add(l);
        }
        return out;
    }

    /** The logged removals: {@code <marked or bare line> ## <yyyy-mm-dd> <reason>}; a line without a dated reason fails. */
    static Set<String> logged(Path f) throws Exception {
        Set<String> out = new HashSet<>();
        if (!Files.isRegularFile(f)) return out;
        for (String l : lines(f)) {
            int i = l.lastIndexOf(" ## ");
            assertTrue(i > 0 && l.substring(i + 4).matches("\\d{4}-\\d{2}-\\d{2} \\S.*"), "api-removals.txt: '<line> ## <yyyy-mm-dd> <reason>' expected: " + l);
            out.add(bare(l.substring(0, i)));
        }
        return out;
    }

    static List<String> unlogged(List<String> removed, Set<String> logged) {
        return removed.stream().filter(l -> !logged.contains(bare(l))).toList();
    }

    @Test
    void thePublicApiIsTheCommittedBaseline() throws Exception {
        List<String> now = surface(javaRoot());
        assertFalse(now.isEmpty(), "no public API found: the modules were not built");
        List<String> was = lines(baseline());
        if (Boolean.getBoolean("rachana.api.surface.write")) {
            List<String> missing = unlogged(removed(was, now), logged(removals()));
            assertEquals(List.of(), missing, "CG5: the write removes lines that java/api-removals.txt does not log (a dated, reviewed reason "
                    + "each); nothing was written");
            Files.writeString(baseline(), HEADER + String.join("\n", now) + "\n");
            was = lines(baseline());
        }
        List<String> removed = new ArrayList<>(was); removed.removeAll(now);
        List<String> added = new ArrayList<>(now); added.removeAll(was);
        assertEquals(List.of(), removed, "CG5: removed or changed API (a breaking change needs the owner and a line in java/api-removals.txt)");
        assertEquals(List.of(), added, "CG5: added API: update java/api-surface.txt in the same commit (-Drachana.api.surface.write=true)");
    }

    /** A released baseline is never rewritten by this test, and what it froze is still there (or its removal is logged). */
    @Test
    void theReleasedBaselinesStillHold() throws Exception {
        List<Path> released;
        try (Stream<Path> s = Files.list(javaRoot())) {
            released = s.filter(p -> p.getFileName().toString().matches("api-surface-\\d+\\.\\d+\\.txt")).sorted().toList();
        }
        if (released.isEmpty()) return;                                   // before the first release
        List<String> now = surface(javaRoot());
        Set<String> logged = logged(removals());
        for (Path r : released) {
            List<String> gone = removed(lines(r), now);
            List<String> stableGone = gone.stream().filter(l -> l.startsWith(S)).toList();
            assertEquals(List.of(), stableGone, "CG5: " + r.getFileName() + " froze these stable lines; they are gone or no longer stable");
            assertEquals(List.of(), unlogged(gone, logged), "CG5: " + r.getFileName() + ": experimental lines removed without a line in api-removals.txt");
        }
    }

    @Test
    void theCheckSeesARemovalADemotionAndAPromotion() throws Exception {
        List<String> was = List.of(S + "a", E + "b", S + "c", E + "d");
        List<String> now = List.of(S + "a", E + "c", S + "d");               // b removed, c demoted, d promoted
        assertEquals(List.of(E + "b", S + "c"), removed(was, now));
        Path log = Files.createTempFile("rachana-api-removals-", ".txt");
        try {
            Files.writeString(log, "# log\nb ## 2026-11-21 reviewed: gone\n");
            assertEquals(List.of(S + "c"), unlogged(removed(was, now), logged(log)));
            Files.writeString(log, "b ## no date\n");
            assertThrows(AssertionError.class, () -> logged(log));
        } finally {
            Files.deleteIfExists(log);
        }
    }
}
