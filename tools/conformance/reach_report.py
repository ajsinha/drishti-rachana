"""Plan H3 (the Rachana-side report): which product classes does Drishti's compute/drishti-rachana main source import? Read only.
    python3 tools/conformance/reach_report.py /path/to/drishti > reach-report.md
The list is the work queue of A1 to A9: it may only shrink."""
import collections
import re
import sys
from pathlib import Path

root = Path(sys.argv[1]) / "compute" / "drishti-rachana" / "src" / "main" / "java"
imp = re.compile(r"^import (?:static )?(com\.ash\.drishti\.(?!rachana\.)[\w.]+?)(?:\.\*)?;", re.M)
spring = re.compile(r"^import (?:static )?(org\.springframework[\w.]*|org\.slf4j[\w.]*|com\.github\.benmanes[\w.]*|jakarta[\w.]*)", re.M)
by, ext, files = collections.defaultdict(set), collections.defaultdict(set), 0
for p in sorted(root.rglob("*.java")):
    files += 1
    t = p.read_text(encoding="utf-8")
    rel = p.relative_to(root).as_posix().replace("com/ash/drishti/rachana/", "")
    for m in imp.findall(t):
        by[m].add(rel)
    for m in spring.findall(t):
        ext[m.rsplit(".", 1)[0] if m.count(".") > 3 else m].add(rel)
print("<!-- Copyright (c) 2026 Ashutosh Sinha. Proprietary: see LICENSE. -->")
print("# R0 reach report: what Drishti's `compute/drishti-rachana` uses outside itself (plan H3)\n")
print(f"Generated by `tools/conformance/reach_report.py` from {files} source files of the reference. Each row is work for A1 to A9; the list may only shrink.\n")
print("## Product classes imported\n\n| Class | Files | Count |\n|---|---|---|")
for k in sorted(by, key=lambda k: (-len(by[k]), k)):
    print(f"| `{k}` | {', '.join(sorted(by[k])[:4])}{' ...' if len(by[k]) > 4 else ''} | {len(by[k])} |")
print("\n## Framework and library imports (to leave Core)\n\n| Package | Files | Count |\n|---|---|---|")
for k in sorted(ext, key=lambda k: (-len(ext[k]), k)):
    print(f"| `{k}` | {', '.join(sorted(ext[k])[:4])}{' ...' if len(ext[k]) > 4 else ''} | {len(ext[k])} |")
