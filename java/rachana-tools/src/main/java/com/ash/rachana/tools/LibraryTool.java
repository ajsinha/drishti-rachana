package com.ash.rachana.tools;

import com.ash.rachana.SutraException;
import com.ash.rachana.SutraProblem;
import com.ash.rachana.lib.Library;
import com.ash.rachana.lib.LibraryBundle;
import com.ash.rachana.lib.LibraryLock;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Stream;

/**
 * The library commands' work on the JVM (LIBRARIES.md 22): {@code build} (regenerate {@code exports} and {@code MANIFEST.sha384}),
 * {@code sign} (a detached Ed25519 signature line in {@code SIGNATURE}), {@code pack} (the deterministic {@code .rlib}), {@code verify}
 * (every rule of {@link Library#load}) and {@code lock} (the {@code rachana.lock} entry of a packed library). No network. Stateless.
 */
public final class LibraryTool {

    private LibraryTool() {
    }

    /** The files of a library folder (path with {@code /} to bytes). */
    public static Map<String, byte[]> read(Path dir) {
        Map<String, byte[]> files = new TreeMap<>();
        try (Stream<Path> s = Files.walk(dir)) {
            for (Path f : s.filter(Files::isRegularFile).toList()) {
                files.put(dir.relativize(f).toString().replace('\\', '/'), Files.readAllBytes(f));
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return files;
    }

    /**
     * Regenerates a library folder's generated parts: {@code exports.fragments} in the manifest (from the fragment files) and
     * {@code MANIFEST.sha384}; removes a {@code SIGNATURE} that the new hashes make stale.
     */
    public static void build(Path dir) {
        String name = dir.getFileName().toString();
        Path manifest = dir.resolve(name + ".rachana-lib.yaml");
        try {
            String text = Files.readString(manifest, StandardCharsets.UTF_8);
            Map<String, byte[]> files = read(dir);
            StringBuilder exports = new StringBuilder("exports:                             # generated by rachana lib build; never typed by hand\n  fragments:");
            List<String> lines = Library.exportLines(files);
            exports.append(lines.isEmpty() ? " []\n" : "\n");
            lines.forEach(l -> exports.append("    ").append(l).append('\n'));
            String kept = text.replaceAll("(?ms)^exports:.*?(?=^[a-z]|\\z)", "");
            Files.writeString(manifest, kept + (kept.endsWith("\n") ? "" : "\n") + exports, StandardCharsets.UTF_8);
            Files.deleteIfExists(dir.resolve(Library.SIGNATURE));
            Files.writeString(dir.resolve(Library.HASHES), Library.hashList(read(dir)), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Adds a signature line ({@code <public key> <signature hex>}) over {@code MANIFEST.sha384} to {@code SIGNATURE}. */
    public static void sign(Path dir, String publicKey, String privateSeed) {
        try {
            byte[] hashes = Files.readAllBytes(dir.resolve(Library.HASHES));
            Path sig = dir.resolve(Library.SIGNATURE);
            String had = Files.exists(sig) ? Files.readString(sig, StandardCharsets.UTF_8) : "";
            Files.writeString(sig, had + publicKey + " " + Ed25519.sign(privateSeed, hashes) + "\n", StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * The library verified and packed into {@code out/<name>-<version>.rlib}.
     *
     * @throws SutraException when the library does not verify
     */
    public static Path pack(Path dir, Path out, Library.Trust trust) {
        LibraryBundle b = LibraryBundle.ofBytes(dir.getFileName().toString(), read(dir), "folder:" + dir);
        Library lib = Library.load(b, trust);
        try {
            Files.createDirectories(out);
            Path f = out.resolve(lib.name() + "-" + lib.version() + ".rlib");
            Files.write(f, b.archive());
            return f;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** The problems of a library folder or {@code .rlib} (empty when it verifies). */
    public static List<SutraProblem> verify(Path dirOrArchive, Library.Trust trust) {
        try {
            load(dirOrArchive, trust);
            return List.of();
        } catch (SutraException e) {
            return e.problems();
        } catch (IllegalArgumentException e) {
            List<SutraProblem> p = new ArrayList<>();
            p.add(new SutraProblem(Library.INVALID, e.getMessage(), new com.ash.rachana.model.SourceLocation(dirOrArchive.toString(), 1, 1)));
            return p;
        }
    }

    /** The lock entry a verified library gets ({@code rachana lib add}). */
    public static LibraryLock.Entry lockEntry(Path dirOrArchive, Library.Trust trust) {
        Library lib = load(dirOrArchive, trust);
        return new LibraryLock.Entry(lib.name(), lib.version(), lib.sha384(), lib.source(), lib.signedBy(), lib.licence());
    }

    private static Library load(Path p, Library.Trust trust) {
        String f = p.getFileName().toString();
        try {
            if (f.endsWith(".rlib")) {
                String name = f.replaceAll("-[0-9]+\\.[0-9]+\\.[0-9]+\\.rlib$", "");
                return Library.load(LibraryBundle.archive(name, Files.readAllBytes(p), "release:" + f), trust);
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return Library.load(LibraryBundle.ofBytes(f, read(p), "folder:" + p), trust);
    }
}
