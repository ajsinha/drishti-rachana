import sys, pathlib
res = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
names = {"formats.yaml": "formats.yaml.json", "world-regions.yaml": "world-regions.yaml.json", "rachana/el/signatures.yaml": "rachana_el_signatures.yaml.json"}
def lit(s):
    o = []
    for ch in s:
        c = ord(ch)
        if ch == '"': o.append('\\"')
        elif ch == '\\': o.append('\\\\')
        elif c < 0x20 or c > 0x7e: o.append('\\u%04x' % c)
        else: o.append(ch)
    return '"' + ''.join(o) + '"'
lines = ["/*", " * Copyright (c) 2026 Ashutosh Sinha. All rights reserved.",
 " * Drishti Rachana. Proprietary: see the LICENSE file at the root of this repository.", " */",
 "package com.ash.proof;", "", "/** GENERATED by the prep step (cut C3): the bundled YAML resources as the JSON of the reference's Jackson read. */",
 "public final class Resources {", "    private Resources() {", "    }", "",
 "    public static java.io.InputStream open(String name) {", "        String[] parts;", "        switch (name) {"]
for n, f in names.items():
    t = (res / f).read_text(encoding="utf-8")
    chunks = [t[i:i+8000] for i in range(0, len(t), 8000)]
    lines.append("            case %s: parts = new String[] {%s}; break;" % (lit(n), ", ".join(lit(c) for c in chunks)))
lines += ["            default: return null;", "        }", "        return new java.io.ByteArrayInputStream(String.join(\"\", parts).getBytes(java.nio.charset.StandardCharsets.UTF_8));", "    }", "}", ""]
out.write_text("\n".join(lines), encoding="utf-8")
