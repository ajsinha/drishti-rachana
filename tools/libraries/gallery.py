"""The library gallery, built with Rachana itself (LIBRARIES.md 8): for each library a static site whose every page is a Sutra.

    python3 tools/libraries/gallery.py [--out DIR] [LIBRARY ...]      (build.py --gallery calls this)

For a library, from its manifest's `exports` (written by `rachana lib build`) and its examples/:
  library.sutra.yaml     the fragments grouped by category, each a link to its page
  <fragment>.sutra.yaml  the fragment's summary and `use:` line; its parameter table, table contract and events as tables
                         (the core/data-table fragment); the live example (the example Sutra's own data and panels); the example source
`rachana build` turns these Sutras into the site (out/<library>/library.html, index.html a redirect to it, <fragment>.html, with the library files the pages use).
No widget is written by hand: a page is the fragment's own example plus Sutra tables over the manifest's metadata.
Needs node (the Rachana command line, js/packages/rachana-cli) and PyYAML."""
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CLI = ROOT / "js" / "packages" / "rachana-cli" / "bin" / "rachana.js"
HEADER = ("# Copyright (c) 2026 Ashutosh Sinha <ajsinha@gmail.com>. All rights reserved.\n"
          "# Drishti Rachana Libraries. Proprietary: see the LICENSE file at the root of this repository.\n"
          "# Generated by tools/libraries/gallery.py; never edited by hand.\n")


def exports(lib: Path):
    manifest = yaml.safe_load(next(lib.glob("*.rachana-lib.yaml")).read_text())
    return manifest, manifest.get("exports", {}).get("fragments", [])


def table(title, rows, columns, span=12):
    """A core/data-table use over inline rows: columns is [(label, field, fmt?)]."""
    return {"use": "core/data-table@1", "as": re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-"),
            "with": {"title": title, "search": False,
                     "rows": rows, "columns": [{"label": l, "bind": f"@.{f}"} for l, f in columns]}}


def fmt_default(v):
    return "" if v is None else (yaml.safe_dump(v, default_flow_style=True).strip().removesuffix("...").strip())


def page(lib_name, manifest, frag, example_text):
    """The Sutra of one fragment's page."""
    name = frag["name"]
    ex = yaml.safe_load(example_text)
    params = frag.get("params") or {}
    rows = []
    for pn, p in params.items():
        kind = p.get("type", "")
        if kind == "table":
            kind = "table(" + ", ".join((p.get("columns") or {}).keys()) + ")"
        elif p.get("options"):
            kind += " (" + " | ".join(str(o) for o in p["options"]) + ")"
        rows.append({"name": pn, "type": kind, "needed": "required" if p.get("required") else (
            "default " + fmt_default(p["default"]) if "default" in p else "optional"), "doc": p.get("doc", "")})
    contract = [{"param": c["param"], "column": cn, "type": cd.get("type", ""), "optional": "optional" if cd.get("optional") else "required",
                 "doc": cd.get("doc", "")} for c in frag.get("contract", []) for cn, cd in (c.get("columns") or {}).items()]
    events = [{"name": e["name"], "payload": ", ".join(f"{k}: {v}" for k, v in (e.get("payload") or {}).items()), "doc": e.get("doc", "")}
              for e in frag.get("events", [])]
    slots = [{"name": k, "doc": (v or {}).get("doc", "") if isinstance(v, dict) else ""} for k, v in (frag.get("slots") or {}).items()]
    needs = frag.get("needs", {})
    head = [f"{frag.get('summary', '')}", "",
            f"Use it as `use: {lib_name}/{name}@{frag['majors'][-1]}`. Needs language level {needs.get('language', '1.0')}.",
            f"Category: {frag.get('category', '')}. Tags: {', '.join(frag.get('tags', []))}."]
    data = {"g_params": {"rows": rows}}
    panels = [{"id": "g-head", "kind": "markdown", "text": "\n".join(head)},
              {**table("Parameters", "$.g_params", [("Name", "name"), ("Type", "type"), ("Needed", "needed"), ("Meaning", "doc")])}]
    if contract:
        data["g_contract"] = {"rows": contract}
        panels.append(table("Table contract", "$.g_contract", [("Parameter", "param"), ("Column", "column"), ("Type", "type"),
                                                               ("Needed", "optional"), ("Meaning", "doc")]))
    if events:
        data["g_events"] = {"rows": events}
        panels.append(table("Events", "$.g_events", [("Event", "name"), ("Payload", "payload"), ("Raised when", "doc")]))
    if slots:
        data["g_slots"] = {"rows": slots}
        panels.append(table("Slots", "$.g_slots", [("Slot", "name"), ("Meaning", "doc")]))
    data["g_source"] = {"rows": [{"line": i + 1, "text": l} for i, l in enumerate(example_text.rstrip().splitlines())]}
    panels.append({"id": "g-example", "kind": "markdown", "text": "**Live example** (the fragment's own example, rendered here)"})
    data.update(ex.get("data") or {})
    panels += ex.get("panels") or []
    panels.append({"id": "g-source-head", "kind": "markdown", "text": f"**Example source** (`{lib_name}/examples/{name}.sutra.yaml`)"})
    panels.append(table("Example source", "$.g_source", [("Line", "line"), ("Text", "text")]))
    libs = sorted(set((ex.get("libraries") or []) + ["core@1", f"{lib_name}@{manifest['version'].split('.')[0]}"]))
    out = {"rachana": 1, "sutra": f"gallery-{name}", "version": 1, "libraries": libs,
           "title": {"id": f"'{lib_name}/{name}'"}, "data": data, "panels": panels}
    for k, v in ex.items():
        if k not in out and k not in ("sutra",):
            out[k] = v
    out["panels"], out["data"] = panels, data
    return out


def index(lib_name, manifest, frags):
    cats = [(c["id"], c["title"]) for c in manifest.get("categories", [])]
    lines = [manifest.get("summary", ""), "", f"{len(frags)} fragments, version {manifest['version']}.", ""]
    known = {c for c, _ in cats}
    groups = cats + ([("", "Other")] if any(f.get("category") not in known for f in frags) else [])
    panels = [{"id": "g-intro", "kind": "markdown", "text": "\n".join(lines)}]
    data = {}
    for cid, title in groups:
        mine = [f for f in frags if (f.get("category") if f.get("category") in known else "") == cid]
        if mine:
            data["g_" + (cid or "other")] = {"rows": [{"name": f["name"], "summary": f.get("summary", "")} for f in mine]}
            panels.append({"use": "core/data-table@1", "as": "cat-" + (cid or "other"),
                           "with": {"title": title, "search": False, "rows": "$.g_" + (cid or "other"),
                                    "columns": [{"label": "Fragment", "bind": "@.name"}, {"label": "What it is", "bind": "@.summary"}]}})
    return {"rachana": 1, "sutra": "library", "version": 1, "libraries": ["core@1"],
            "title": {"id": f"'{manifest.get('title', lib_name)} library'"}, "data": data, "panels": panels}


def dump(path: Path, doc):
    path.write_text(HEADER + yaml.safe_dump(doc, sort_keys=False, width=1000, allow_unicode=True))


def navigation(site: Path, lib_name: str, frags, manifest):
    """Core has no navigation link (a link of a view is the host's to open), so the page host adds the anchors between pages: a back link
    on each fragment page and, on the library page, the list of fragment pages by category. The content of every page stays Sutra."""
    from html import escape
    known = [(c["id"], c["title"]) for c in manifest.get("categories", [])]
    groups = "".join(f"<h3>{escape(t)}</h3><ul>" + "".join(f'<li><a href="{f["name"]}.html">{escape(f["name"])}</a></li>'
                                                          for f in frags if f.get("category") == cid) + "</ul>"
                     for cid, t in known if any(f.get("category") == cid for f in frags))
    for page in site.glob("*.html"):
        if page.stem == "library":
            nav = f'<nav class="gallery-nav"><b>{escape(lib_name)} fragments</b>{groups}</nav>'
        else:
            nav = '<nav class="gallery-nav"><a href="library.html">All fragments of ' + escape(lib_name) + "</a></nav>"
        text = page.read_text()
        page.write_text(text.replace("<rachana-view ", nav + "\n<rachana-view ", 1))


def build(lib: Path, out_root: Path):
    manifest, frags = exports(lib)
    work = out_root / "src" / lib.name
    shutil.rmtree(work, ignore_errors=True)
    (work / "sutras").mkdir(parents=True)
    dump(work / "sutras" / "library.sutra.yaml", index(lib.name, manifest, frags))
    for f in frags:
        ex = lib / "examples" / f"{f['name']}.sutra.yaml"
        if not ex.is_file():
            sys.exit(f"{lib.name}/{f['name']}: no example (examples/{f['name']}.sutra.yaml)")
        dump(work / "sutras" / f"{f['name']}.sutra.yaml", page(lib.name, manifest, f, ex.read_text()))
    site = out_root / "site" / lib.name
    shutil.rmtree(site, ignore_errors=True)
    r = subprocess.run(["node", str(CLI), "build", "--src", str(work), "--out", str(site), "--level", "1.2", "--libs", str(lib.parent)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout + r.stderr)
        sys.exit(f"gallery of {lib.name}: rachana build failed")
    navigation(site, lib.name, frags, manifest)
    (site / "index.html").write_text('<!doctype html><meta charset=utf-8><meta http-equiv=refresh content="0; url=library.html"><a href="library.html">The ' + lib.name + ' library</a>\n')
    print(f"  gallery {site}: {len(frags)} fragment page(s) + index")
    return site


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("libraries", nargs="*")
    ap.add_argument("--out", default=str(ROOT / "results" / "libraries" / "gallery"))
    a = ap.parse_args()
    root = ROOT / "libraries"
    libs = [root / n for n in a.libraries] if a.libraries else sorted(p for p in root.iterdir() if p.is_dir())
    for lib in libs:
        build(lib, Path(a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
